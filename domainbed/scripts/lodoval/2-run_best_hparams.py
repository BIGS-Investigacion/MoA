#!/usr/bin/env python3
"""
Launches the experiments with the optimal hparams_seed for each
(dataset, algorithm, model, trial_seed, test_env), reading the CSV generated by
1-get_best_lodoval.py (--out).

One `python train_all.py <Name> ...` is launched for each unique combination of
(dataset, algorithm, model, trial_seed, hparams_seed, test_env). If two rows
request exactly the same thing, it is executed only once.

Example (local):
  python 2-run_best_hparams best.csv --name Final --dry-run

Example (Slurm, one sbatch per run, from the login node):
  python 2-run_best_hparams best.csv --name Final \
      --slurm --partition gpu --gres gpu:1 --time 12:00:00 --mem 32G --dry-run
"""
import argparse
import os
import shlex
import subprocess
import sys
import time
from pathlib import Path

import pandas as pd

REQUIRED_COLS = ["dataset", "algorithm", "model", "trial_seed",
                 "test_env", "hparams_seed"]


def build_jobs(df):
    """Return the sorted set of unique runs."""
    jobs = set()
    for row in df.to_dict("records"):
        jobs.add((
            str(row["dataset"]), str(row["algorithm"]), str(row["model"]),
            int(row["trial_seed"]), int(row["hparams_seed"]),
            int(row["test_env"]),
        ))
    return sorted(jobs)


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("csv", help="CSV from lodo_select.py (--out)")

    # Framework
    p.add_argument("--name", default="Test",
                   help="Positional argument of train_all.py (experiment name)")
    p.add_argument("--script", default="train_all.py")
    p.add_argument("--python", default=None,
                   help="Interpreter (default: the current one; with --slurm 'python')")
    p.add_argument("--data-dir", default="/home/jesferrom/datasets/DG")
    p.add_argument("--output-dir", default="TRAIN_OUTPUT")
    p.add_argument("--seed", type=int, default=1,
                   help="Main seed (it is not in the CSV)")
    p.add_argument("--es-val", type=int, default=6)
    p.add_argument("--l-aux", action=argparse.BooleanOptionalAction, default=True,
                   help="Passes --l_aux (disable with --no-l-aux)")
    p.add_argument("--lodoval", action="store_true",
                   help="Passes --lodoval to train_all.py (disabled by default)")
    p.add_argument("--model", default=None,
                   help="Forces the value of --model (if the name in the CSV "
                        "does not match the one train_all.py expects)")
    p.add_argument("--extra", default="",
                   help="Extra arguments for train_all.py, in quotes")

    # Flag names in the new framework (adjust them if they differ)
    p.add_argument("--test-env-flag", default="--test_envs",
                   help="Flag to set the test env. Pass '' to not send it "
                        "if train_all.py already loops over all environments")

    # Filters
    p.add_argument("--datasets", nargs="*", default=None)
    p.add_argument("--algorithms", nargs="*", default=None)
    p.add_argument("--models", nargs="*", default=None)
    p.add_argument("--trial-seeds", type=int, nargs="*", default=None)
    p.add_argument("--test-envs", type=int, nargs="*", default=None)

    # Execution
    p.add_argument("--dry-run", action="store_true", help="Only print the commands")
    p.add_argument("--stop-on-error", action="store_true")

    # Slurm
    p.add_argument("--slurm", action="store_true",
                   help="Submit one sbatch per run instead of running locally")
    p.add_argument("--job-prefix", default="best_hp")
    p.add_argument("--log-dir", default="slurm_logs")
    p.add_argument("--partition", default=None)
    p.add_argument("--account", default=None)
    p.add_argument("--gres", default=None, help="e.g. gpu:1")
    p.add_argument("--time", default=None, help="e.g. 12:00:00")
    p.add_argument("--mem", default=None, help="e.g. 32G")
    p.add_argument("--cpus-per-task", type=int, default=None)
    p.add_argument("--sbatch-extra", default="",
                   help="Extra args for sbatch (e.g. \"--qos=normal\")")
    p.add_argument("--setup-cmd",
                   default="source /etc/profile; "
                           "source ~/miniconda3/etc/profile.d/conda.sh; "
                           "conda activate MoA",
                   help="Commands to run before training inside the job")
    args = p.parse_args()

    python_bin = args.python or ("python" if args.slurm else sys.executable)
    cuda_conf = "expandable_segments:True,max_split_size_mb:128"

    df = pd.read_csv(args.csv)
    missing = [c for c in REQUIRED_COLS if c not in df.columns]
    if missing:
        sys.exit(f"ERROR: missing columns in the CSV: {missing}")

    for col, values in (("dataset", args.datasets),
                        ("algorithm", args.algorithms),
                        ("model", args.models),
                        ("trial_seed", args.trial_seeds),
                        ("test_env", args.test_envs)):
        if values is not None:
            df = df[df[col].isin(values)]
    if df.empty:
        sys.exit("No rows left after applying the filters.")

    jobs = build_jobs(df)
    total = len(jobs)
    print(f"Rows in the CSV: {len(df)} | Runs to execute: {total}")

    env = os.environ.copy()
    env["PYTORCH_CUDA_ALLOC_CONF"] = cuda_conf

    failures, submitted = [], 0
    for n, key in enumerate(jobs, start=1):
        dataset, algorithm, model, trial_seed, hparams_seed, test_env = key
        model_arg = args.model or model

        cmd = [python_bin, args.script, args.name,
            "--data_dir", args.data_dir,
            "--output_dir", args.output_dir,
            "--algorithm", algorithm,
            "--dataset", dataset,
            "--model", model_arg,
            "--seed", str(args.seed),
            f"--es_val={args.es_val}",
            f"--hparams_seed={hparams_seed}",
            f"--trial_seed={trial_seed}",
            "--test_envs", str(test_env)]

        if args.l_aux:
            cmd.append("--l_aux")
        if args.lodoval:
            cmd.append("--lodoval")
        cmd += shlex.split(args.extra)

        print("\n" + "=" * 60)
        print(f"Run {n} / {total}")
        print(f"  {dataset} | {algorithm} | {model_arg}")
        print(f"  trial_seed={trial_seed}  hparams_seed={hparams_seed}  "
              f"test_env={test_env}")
        print("=" * 60)

        if args.slurm:
            job_name = (f"{args.job_prefix}_{dataset}_{model_arg}_TS{trial_seed}"
                        f"_HP{hparams_seed}_TE{test_env}")
            wrap = "; ".join([
                args.setup_cmd,
                f"export PYTORCH_CUDA_ALLOC_CONF={cuda_conf}",
                'echo "[$(date +%T)] Initializing job"',
                shlex.join(cmd),
                'echo "[$(date +%T)] Job Finished"',
            ])
            sbatch = ["sbatch", f"--job-name={job_name}",
                      f"--output={args.log_dir}/{job_name}-%j.out"]
            for flag, value in (("--partition", args.partition),
                                ("--account", args.account),
                                ("--gres", args.gres),
                                ("--time", args.time),
                                ("--mem", args.mem),
                                ("--cpus-per-task", args.cpus_per_task)):
                if value is not None:
                    sbatch.append(f"{flag}={value}")
            sbatch += shlex.split(args.sbatch_extra)
            sbatch += ["--wrap", wrap]

            if args.dry_run:
                print(shlex.join(sbatch))
                continue

            Path(args.log_dir).mkdir(parents=True, exist_ok=True)
            res = subprocess.run(sbatch, capture_output=True, text=True)
            if res.returncode == 0:
                print(f"  {res.stdout.strip()}")
                submitted += 1
            else:
                failures.append((key, res.returncode))
                print(f"ERROR: sbatch failed: {res.stderr.strip()}")
                if args.stop_on_error:
                    break
            continue

        if args.dry_run:
            print(shlex.join(cmd))
            continue

        t0 = time.time()
        status = subprocess.run(cmd, env=env).returncode
        print(f"\nRun {n} finished (exit {status}, {time.time() - t0:.0f}s)")
        if status != 0:
            failures.append((key, status))
            print(f"ERROR: run {key} failed")
            if args.stop_on_error:
                break

    print("\n" + "=" * 60)
    extra = f" | submitted to Slurm: {submitted}" if args.slurm else ""
    print(f"Runs: {total} | failed: {len(failures)}{extra}")
    for key, status in failures:
        print(f"  FAILED (exit {status}): {key}")
    print("=" * 60)
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()